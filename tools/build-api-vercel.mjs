/**
 * Empacota a API Hono (+ workspaces TS) num function handler Vercel.
 * Saída: api/[[...route]].js (Node 20, CJS).
 */
import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "api");
const outfile = path.join(outDir, "[[...route]].js");

fs.mkdirSync(outDir, { recursive: true });

await esbuild.build({
  absWorkingDir: root,
  entryPoints: [path.join(root, "apps/api/src/vercel.ts")],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  outfile,
  logLevel: "info",
  // Mantém deps nativas/pesadas fora do bundle; o runtime Vercel resolve de node_modules.
  external: ["@supabase/supabase-js", "dotenv"],
  alias: {
    "@afd/economy": path.join(root, "packages/economy/src/index.ts"),
    "@afd/shared-types": path.join(root, "packages/shared-types/src/index.ts"),
  },
  banner: {
    js: "/* AFD economy API — generated by tools/build-api-vercel.mjs */",
  },
  // Vercel Node espera o handler em module.exports (não só .default).
  footer: {
    js: "module.exports = module.exports.default ?? module.exports;",
  },
});

console.log(`[build-api-vercel] wrote ${path.relative(root, outfile)}`);
